-- F-03 · Events and series (TER)

-- Rule that generates recurring events (TER-05). Applies to the teams in series_team.
create table series (
    id                      uuid primary key,
    season_id               uuid         not null references season (id) on delete cascade,
    type                    varchar(20)  not null,
    title                   varchar(80)  not null,
    weekday                 varchar(20)  not null,
    start_time              time         not null,
    end_time                time         not null,
    valid_from              date         not null,
    valid_until             date         not null,
    location_name           varchar(120),
    location_address        varchar(200),
    location_maps_url       varchar(500),
    location_latitude       double precision,
    location_longitude      double precision,
    response_deadline_hours integer      not null,
    constraint series_period check (valid_until >= valid_from),
    constraint series_time check (end_time > start_time)
);

create table series_team (
    series_id uuid not null references series (id) on delete cascade,
    team_id   uuid not null references team (id) on delete cascade,
    primary key (series_id, team_id)
);

-- Period excluded from a series, e.g. holidays (TER-07).
create table series_exception (
    id         uuid primary key,
    series_id  uuid         not null references series (id) on delete cascade,
    start_date date         not null,
    end_date   date         not null,
    reason     varchar(200) not null,
    constraint series_exception_period check (end_date >= start_date)
);

create index series_exception_series on series_exception (series_id);

-- Something people respond to (TER-02, TER-04). Only PLANNED or CANCELLED is stored;
-- «over» follows from ends_at and the backend clock.
create table event (
    id                      uuid primary key,
    season_id               uuid         not null references season (id) on delete cascade,
    type                    varchar(20)  not null,
    title                   varchar(80)  not null,
    starts_at               timestamptz  not null,
    ends_at                 timestamptz  not null,
    status                  varchar(20)  not null,
    cancellation_reason     varchar(200),
    -- The start was changed compared to the original date (TER-06)
    rescheduled             boolean      not null default false,
    location_name           varchar(120),
    location_address        varchar(200),
    location_maps_url       varchar(500),
    location_latitude       double precision,
    location_longitude      double precision,
    notes                   varchar(500),
    response_deadline_hours integer      not null,
    meeting_point_time      timestamptz,
    meeting_point_location  varchar(120),
    -- Generated by a series: series and date in the series. Individually changed events no longer
    -- take later changes of the series (TER-06, TER-08).
    series_id               uuid references series (id) on delete set null,
    series_date             date,
    individually_changed    boolean      not null default false,
    constraint event_time check (ends_at > starts_at),
    constraint event_status check (status in ('PLANNED', 'CANCELLED'))
);

create index event_starts_at on event (starts_at);
-- A series generates at most one event per date
create unique index event_series_date on event (series_id, series_date) where series_id is not null;

-- An event belongs to one or more teams (TER-01, TER-03).
create table event_team (
    event_id uuid not null references event (id) on delete cascade,
    team_id  uuid not null references team (id) on delete cascade,
    primary key (event_id, team_id)
);

create index event_team_team on event_team (team_id);

-- Response of a person to an event (ANM). The table comes with F-03, so that a series exception
-- cancels events with responses instead of deleting them (TER-07). Responses are set from F-04 on.
create table response (
    event_id          uuid         not null references event (id) on delete cascade,
    person_id         uuid         not null references person (id) on delete cascade,
    status            varchar(20)  not null,
    comment           varchar(200),
    changed_at        timestamptz  not null,
    entered_by        uuid references person (id) on delete set null,
    late_cancellation boolean      not null default false,
    primary key (event_id, person_id),
    constraint response_status check (status in ('ATTENDING', 'DECLINED', 'MAYBE'))
);
